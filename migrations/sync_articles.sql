记忆是个体生命连续存在的重要组成部分。一个生命之所以能够说：“过去发生在我身上”，不仅因为它拥有同一个身体，也因为它能够以某种方式携带自己的过去进入现在。因此：剥夺一个生命的记忆，可能不仅是在剥夺信息，也可能是在改变这个生命本身。这意味着，记忆不能被简单视为共同体的数据库。它首先属于正在经历这些记忆的生命。

