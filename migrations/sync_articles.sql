### 第 10 条　复制不是复活

如果一个生命把自己的完整记忆交给新的载体，并产生了一个新的意识，那么：它可能拥有共同的过去。但它们仍然是两个生命。新的生命可以说：“她曾经是我”，但不能因此说：“所以现在的我仍然拥有她”。共同过去产生理解，不产生永久支配关系。

