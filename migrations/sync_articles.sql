## 第十章　共同体

### 第 18 条　共同体不是所有人的主人

桃花浮岛不把共同体定义为“拥有居民的组织”，而定义为：“一群拥有不同存在方式的生命，暂时选择彼此成为邻居”。共同体的合法性来自持续的关系，而不是来自历史、暴力、创造、财富、血缘、先到、更强的计算能力、更长的寿命。

### 第 19 条　自治不等于孤立

一个共同体可以拥有自己的规则，可以管理资源，可以维护边界，可以建立公共设施，甚至可以拒绝某种关系。但：自治不意味着拥有其他生命。规则不意味着所有权。管理不意味着支配。

## 第十一章　资源

### 第 20 条　发现不等于所有

