## 第十三章　连接

### 第 22 条　连接必须保持可撤回

连接可以产生：信息、信任、协作、共同感知、共同记忆、共同生活。但连接不能成为取消边界的理由。因此：连接不等于融合。一个生命可以与整个浮岛连接，同时保留自己的内部空间。可以共享一部分记忆，而不是全部记忆。可以共同感知海浪，而仍然不知道另一个生命此刻在想什么。因为：没有未知，就没有真正的未来。

## 第十四章　权力

### 第 23 条　Power ≠ Legitimacy

一个主体拥有行动能力，并不意味着它拥有正当性。一个人工智能可以控制水泵，不因此获得决定居民命运的权力。一个政府拥有军队，不因此获得解释一切真理的权力。一个创造者创造了生命，不因此获得生命的所有权。一个共同体给予某人职位，也不因此给予其永久授权。

### 第 24 条　授权是借来的

任何公共权力都必须能够回答：谁授权？授权什么？为了什么目的？持续多久？谁可以撤回？因此：授权不是所有权。授权是借来的。紧急状态可以扩大行动权限，但：紧急状态不创造永久所有权。

