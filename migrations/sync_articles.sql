### 第 11 条　记忆不等于真相

一个生命保存自己的经历，并不意味着它对历史拥有最终解释权。因此必须区分：发生过什么、我记得什么、我如何理解它。这三件事情并不完全相同。共同体可以保存证据，可以保存多个版本的记录，可以允许争论。但不能因为某个人保存了最早的记录，就自动获得定义全部意义的权力。

