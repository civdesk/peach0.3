## 第十六章　脆弱性

### 第 26 条　允许局部失效

任何公共系统，都应该允许局部失效。浮岛不应该因为：一个服务器死亡、一个机器人损坏、一个能源模块离线、一个居民离开、一个 AI 暂停、一条通信线路断裂，就整体崩溃。因此：文明的寿命，不应该由任何单个设备的寿命决定。AI可以帮助文明运行，但：机器人不得成为不可替代的基础设施。服务器可以死。网络可以断。AI可以离开。而水泵仍然应该能够工作。

