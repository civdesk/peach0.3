## 第八章　关系可以被改变

### 第 14 条　关系权

任何生命都有权：建立关系、改变关系、暂停关系、拒绝关系、退出关系，也有权重新建立关系。这就是为什么桃花浮岛使用“临接”而不是“归属”。一个生命可以临接共同体，共同体也可以接受它。但双方都保留重新协商关系的权利。

