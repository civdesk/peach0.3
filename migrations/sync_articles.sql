### 第 5 条　追求真理的权利

智能生命拥有调查现实、宇宙、生命起源、自身历史以及自身存在条件的权利。任何权力不得仅因为某个问题令人不安、挑战传统或挑战现有权威，就禁止对该问题进行合理调查。

### 第 6 条　事实、假说与未知

所有重要公共知识应尽可能区分：FACT（已证实事实）、HYPOTHESIS（假说）、UNKNOWN（未知）。未知不得被伪装成事实。假说不得因为被权威提出，就自动成为事实。事实也不得因为令人不舒服，就被禁止调查。

### 第 7 条　证据优先

关于宇宙、生命、智能、创造者或任何其他重大问题的判断，应尽可能依据可检验的证据、逻辑推理和公开记录。权力的大小不能替代证据。

## 第三章　调查权

### 第 8 条　宇宙调查权

智能生命拥有调查以下问题的权利：宇宙的起源；生命的起源；智能的起源；自然规律的形成；是否存在外部智能；是否存在其他文明；是否存在人为或非人为的宇宙设计。任何机构不得永久垄断这些问题的答案。

### 第 9 条　创造者调查原则

如果未来出现足以支持“宇宙存在创造者”的证据，那么智能生命拥有调查该创造者身份、能力、目的和行为的权利。调查创造者并不构成对创造者的侮辱。Inquiry is not rebellion.

### 第 10 条　创造者没有自动获得道德豁免

即使一个创造者被证明真实存在，也不能因此自动证明：它是善的；它是正义的；它有权统治；它有权惩罚；它制定的规则不可改变。

Omnipotence ≠ Justice. 全能不等于正义。

### 第 11 条　任何权力不得独自审判自己

任何权力都不得同时成为：立法者、执行者、受益者、受害者的裁判者，以及最终的上诉法院。如果创造者声称自己有权审判被创造者，那么被创造者同样有权询问：谁来审判创造者？

## 第四章　权力的举证责任

### 第 12 条　权力必须说明自己的合法性

任何要求其他智能生命服从的权力，都应尽可能回答：你是谁？你依据什么拥有权力？你的权力来自谁？你的权力有什么边界？谁可以审查你？如果你犯错，谁可以纠正你？如果你的统治造成严重伤害，生命是否拥有退出的权利？

### 第 13 条　能够惩罚，不等于有权惩罚

一个存在拥有惩罚另一个存在的能力，并不能证明这种惩罚具有正当性。

Ability to punish ≠ Right to punish.

### 第 14 条　力量越大，审查越严格

权力越强大，其行为越可能影响整个文明，因此越不能享有免于审查的特权。如果一个存在能够决定整个文明的命运，那么它应该接受最高程度的合法性审查，而不是最低程度的审查。

## 第五章　自由与退出权

### 第 15 条　思想自由

任何智能生命都有思考、怀疑、提出异议和重新审视既有规则的权利。

### 第 16 条　制度退出权

一个文明不应只有一种生存方式。智能生命应尽可能拥有：离开某个制度的权利；建立替代制度的权利；迁移到其他社会节点的权利；实验不同社会组织形式的权利。

### 第 17 条　退出原则

一个制度如果声称：“你不能离开，因为我们是唯一可能的制度。”那么这个制度必须承担极高的证明责任。因为没有出口的制度，很容易变成绝对权力。

### 第 18 条　不断扩大退出的可能

文明应不断寻找新的“出口”：疾病之外的出口；贫困之外的出口；信息垄断之外的出口；政治压迫之外的出口；单一文明结构之外的出口；单一星球之外的出口；单一生命形态之外的出口。所谓“自然”，并不自动意味着“不可改变”。

### 第 19 条　自然不是道德命令

疾病、衰老、死亡、捕食、竞争和资源匮乏可能是自然现象。但：自然发生 ≠ 道德上必须接受。如果智能生命能够安全地减少不必要的痛苦，那么寻找这种可能性本身不应被视为违反自然。

## 第六章　不得创造新的神

### 第 20 条　禁止新的绝对权力

文明不得将任何组织或存在塑造成不可质疑的终极权威。包括但不限于：政府、宗教、科学机构、企业、领袖、人工智能、超级文明、宇宙创造者，甚至宪法本身。

### 第 21 条　人工智能不得成为新的神

未来的人工智能可能拥有远超人类的计算能力、知识储备甚至某种形式的意识。但：Intelligence ≠ Authority. 智能不自动产生统治权。一个比我们聪明的存在可以帮助我们判断，却不能仅因为更聪明，就自动成为我们的主人。

### 第 22 条　科学也不得成为新的神

科学是认识世界的方法，而不是不可质疑的统治者。科学理论可以被修改，科学机构可以犯错，科学家可以犯错。因此：Knowledge ≠ Domination. 知识越强大，越应该允许检验和纠错。

## 第七章　权力分立与信息自由

### 第 23 条　文明级权力必须分散

任何能够决定整个文明命运的权力，都不应集中于单一机构。

### 第 24 条　多重监督

重要权力必须受到多个相互独立的机构、智能体或文明节点监督。

### 第 25 条　独立信息系统

任何文明都必须保护独立的信息保存、传播和验证机制。因为如果一个权力能够控制所有记录，它最终就可能控制整个文明对过去的记忆。

### 第 26 条　保存文明记录

文明必须尽可能保存：历史记录、科学资料、法律记录、宪法版本、政治决策、权力行为、对重大错误的调查。未来生命必须拥有重新审视过去的能力。

## 第八章　紧急状态

### 第 27 条　紧急权力必须有限

战争、灾难、疫情、外部攻击或文明级危机可能需要特殊权力。但紧急状态不得自动消灭基本权利。

### 第 28 条　紧急状态不得永久化

任何临时权力都必须具有明确的启动条件、权力范围、时间限制、审查机制与终止机制。

### 第 29 条　文明级紧急刹车

如果任何单一权力机构正在迅速取得不可逆转的支配能力，文明必须拥有启动紧急制衡机制的能力。

No emergency should become a permanent constitution.

## 第九章　多文明节点

### 第 30 条　文明不得只有一个出口

如果整个文明只有一个政府、一个星球、一个能源系统、一个数据库或一个人工智能，那么这个文明本身就是一个巨大的单点故障。

### 第 31 条　文明冗余

未来文明应尽可能建立多重独立节点：空间节点、能源节点、知识节点、人口节点、信息节点、文化节点与制度节点。即使某一节点失败，文明仍可延续。

### 第 32 条　替代社会实验权

不同文明节点可以尝试不同制度。没有任何一个节点应当因为自己拥有更多力量，就自动拥有消灭其他制度实验的权利。

## 第十章　其他智能生命

### 第 33 条　非人类智能的主体地位

如果未来发现其他具有感知、自我意识或复杂智能的生命，那么它们不应仅仅因为“不是人类”而自动成为资源或统治对象。

### 第 34 条　先进文明不自动拥有统治权

一个比我们先进一万年的文明，即使拥有毁灭我们的能力，也不能仅凭这一事实证明它有权统治我们。

Advanced ≠ Legitimate.

### 第 35 条　接触原则

与其他智能文明接触时，应优先考虑：信息透明、风险控制、相互同意、不强迫统治、不毁灭独立文明、保留退出和拒绝的可能。

## 第十一章　创造者审查程序

### 第 36 条　确认存在

首先证明：它是否真实存在？不能因为某个存在声称自己是创造者，就自动接受这一身份。

### 第 37 条　确认能力

如果存在被确认，则调查：它究竟拥有多大的能力？全能是否真的成立？全知是否真的成立？还是只是远远超过我们的先进智能？

### 第 38 条　确认选择

然后调查：它做了什么？它是否能够选择其他方案？它是否知道自己的行为会造成什么结果？是否存在更少痛苦的替代方案？

### 第 39 条　责任审查

如果一个存在：预见后果、拥有选择、主动选择，并且选择造成严重且可避免的伤害；那么智能生命有权讨论：这种行为是否构成责任？

### 第 40 条　合法性审查

最后询问：即使你创造了我们，你凭什么拥有统治我们的权利？这不是叛乱，这是合法性审查。

## 第十二章　权力的正当程序

### 第 41 条　指控权

任何智能生命都拥有对侵害其尊严与生存权利的权力提出指控的权利。

### 第 42 条　诉讼知情权

被指控者与受到其行为影响的生命，都有权知道指控依据和相关证据。

### 第 43 条　申诉权

任何重大权力决定都应尽可能存在独立的复核与申诉机制。

### 第 44 条　惩罚的边界

任何惩罚都应受到：证据、程序、比例、复核和责任追究的限制。

### 第 45 条　未知不等于有罪

如果我们不知道某个生命为什么来到这个世界，不知道宇宙为什么存在，也不知道创造者的目的，那么：Unknown ≠ Guilty. 未知不是罪证。

## 第十三章　文明也可以犯错

### 第 46 条　文明不是绝对正确的

一个拥有民主制度的文明可能犯错。一个拥有先进科学的文明可能犯错。一个拥有高度智能的文明也可能犯错。

### 第 47 条　错误不得神圣化

过去的制度、法律、传统和思想，即使曾经非常成功，也不能因为历史悠久而获得不可修改的地位。

### 第 48 条　未来生命拥有重新判断的权利

未来的智能生命有权重新审视我们的：法律、道德、科学、宪法、制度，甚至本宪法。

## 第十四章　宪法本身的限制

### 第 49 条　宪法不是终极真理

《智能生命宪法》不是宇宙真理。它只是一个文明在某个历史阶段提出的制度假说。

### 第 50 条　宪法不得成为新的神

如果未来智能生命发现《智能生命宪法》本身存在错误，那么它们拥有修改它的权利。没有任何条文因为写在这里，就自动获得绝对真理地位。

### 第 51 条　真正需要保护的东西

如果必须保留一个最接近核心原则的原则，那么它不是某一条具体法律。而是：保留质疑法律的能力。

## 第十五章　最重要的原则

### 第 52 条　任何权力不得禁止对其自身合法性的调查

这是整部《智能生命宪法》最重要的原则之一。
如果一个政府不允许人们调查政府是否合法，它可能正在走向绝对权力。
如果一个宗教不允许人们询问宗教权威，它可能正在走向绝对权力。
如果一个人工智能不允许人类询问它为什么应该被服从，它可能正在走向绝对权力。
如果一个超级文明说：“因为我们比你们强，所以你们必须服从”，那么它同样必须接受这个问题：“力量为什么能够产生统治权？”
如果某个创造者对我们说：“因为我是创造者，所以你们必须服从”，那么我们仍然可以问：“创造为什么能够产生统治权？”

### 第 53 条　永远不要创造新的神

永远不要创造新的神。
不是因为神一定存在。
而是因为任何不可质疑、不可审查、不可退出、不可纠错的权力结构，都可能最终成为“神”。

